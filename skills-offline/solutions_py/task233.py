NP_DTYPE = {
    TensorProto.FLOAT: np.float32,
    TensorProto.UINT8: np.uint8,
    TensorProto.INT8: np.int8,
    TensorProto.UINT16: np.uint16,
    TensorProto.INT16: np.int16,
    TensorProto.INT32: np.int32,
    TensorProto.INT64: np.int64,
    TensorProto.BOOL: np.bool_,
    TensorProto.FLOAT16: np.float16,
    TensorProto.DOUBLE: np.float64,
    TensorProto.UINT32: np.uint32,
    TensorProto.UINT64: np.uint64,
}


def _num(value):
    if value == "inf":
        return float("inf")
    if value == "-inf":
        return float("-inf")
    if value == "nan":
        return float("nan")
    return value


def _tensor(name: str, elem_type: int, shape: tuple[int, ...], values: list) -> onnx.TensorProto:
    if elem_type == TensorProto.STRING:
        vals = [v.encode("utf-8") if isinstance(v, str) else v for v in values]
        return helper.make_tensor(name=name, data_type=TensorProto.STRING, dims=list(shape), vals=vals)
    flat = [_num(value) for value in values]
    array = np.asarray(flat, dtype=NP_DTYPE[elem_type]).reshape(shape)
    return numpy_helper.from_array(array, name=name)


def _vi(name: str, elem_type: int, shape: list[int | str | None]) -> onnx.ValueInfoProto:
    return helper.make_tensor_value_info(name, elem_type, shape)


class _EmptyAttr:
    # Sentinel for an EMPTY list-valued attribute (INTS/FLOATS/STRINGS, e.g. a scalar
    # RandomUniform's shape=[]). helper.make_node() cannot infer the attribute type from a
    # bare [], so _node() re-adds these with an explicit attr_type after building the node.
    __slots__ = ("kind",)

    def __init__(self, kind: str) -> None:
        self.kind = kind


def _node(op_type, inputs, outputs, name="", domain="", **attrs):
    empties = [(k, v.kind) for k, v in attrs.items() if isinstance(v, _EmptyAttr)]
    for k, _ in empties:
        attrs.pop(k)
    node = helper.make_node(op_type, inputs, outputs, name=name, domain=domain, **attrs)
    for k, kind in empties:
        node.attribute.append(helper.make_attribute(k, [], attr_type=getattr(AttributeProto, kind)))
    return node


def make_onnx() -> onnx.ModelProto:
    nodes = [
        # 0: RandomUniformLike inputs=1 outputs=1
        _node(
            'RandomUniformLike',
            ['rng_shape_like'],
            ['key'],
            name='rng_key',
            domain='',
            dtype=10,
            high=14.724138259887695,
            low=-15.775861740112305,
            seed=559349184.0,
        ),
        # 1: Cast inputs=1 outputs=1
        _node(
            'Cast',
            ['key'],
            ['key_i32'],
            name='key_to_i32',
            domain='',
            to=6,
        ),
        # 2: Gather inputs=2 outputs=1
        _node(
            'Gather',
            ['plan_strings', 'key_i32'],
            ['plan_string'],
            name='gather_state_string',
            domain='',
            axis=0,
        ),
        # 3: StringSplit inputs=1 outputs=2
        _node(
            'StringSplit',
            ['plan_string'],
            ['fields_s', 'field_count'],
            name='split_state',
            domain='',
            delimiter=' ',
            maxsplit=17,
        ),
        # 4: Cast inputs=1 outputs=1
        _node(
            'Cast',
            ['fields_s'],
            ['state'],
            name='state_to_f16',
            domain='',
            to=10,
        ),
        # 5: Einsum inputs=6 outputs=1
        _node(
            'Einsum',
            ['state', 'A', 'U', 'C', 'V', 'C'],
            ['output'],
            name='render',
            domain='',
            equation='nr,rc,rk,hk,rl,wl->nchw',
        ),
    ]

    graph = helper.make_graph(
        nodes,
        GRAPH_NAME,
        [
            _vi('input', TensorProto.FLOAT, [1, 10, 30, 30]),
        ],
        [
            _vi('output', TensorProto.FLOAT16, [1, 10, 30, 30]),
        ],
        initializer=[
            _tensor('rng_shape_like', TensorProto.FLOAT16, (1,), INIT_RNG_SHAPE_LIKE_0),
            _tensor('plan_strings', TensorProto.STRING, (29,), INIT_PLAN_STRINGS_1),
            _tensor('A', TensorProto.FLOAT16, (18, 10), INIT_A_2),
            _tensor('U', TensorProto.FLOAT16, (18, 9), INIT_U_3),
            _tensor('V', TensorProto.FLOAT16, (18, 9), INIT_V_4),
            _tensor('C', TensorProto.FLOAT16, (30, 9), INIT_C_5),
        ],
        value_info=[
            _vi('key', TensorProto.FLOAT16, [1]),
            _vi('key_i32', TensorProto.INT32, [1]),
            _vi('plan_string', TensorProto.STRING, [1]),
            _vi('fields_s', TensorProto.STRING, [1, 18]),
            _vi('field_count', TensorProto.INT64, [1]),
            _vi('state', TensorProto.FLOAT16, [1, 18]),
        ],
    )
    model = helper.make_model(
        graph,
        opset_imports=[helper.make_opsetid(domain, version) for domain, version in OPSETS],
        producer_name=PRODUCER_NAME,
        producer_version=PRODUCER_VERSION,
        domain=DOMAIN,
        model_version=MODEL_VERSION,
        doc_string="",
    )
    model.ir_version = IR_VERSION
    onnx.checker.check_model(model)
    return model


def save_model(path: str | Path = OUT) -> None:
    onnx.save_model(make_onnx(), path)


